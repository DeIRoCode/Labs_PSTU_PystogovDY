#include <iostream>
#include <iomanip>
#include <cmath>

using namespace std;

int main()
{
    setlocale(LC_ALL, "ru_RU.UTF-8");

    double a = 0.1;       // начало диапазона
    double b = 1.0;       // конец диапазона
    int k = 10;           // количество шагов
    int N = 30;           // количество членов ряда
    double eps = 0.0001;  // точность

    double step = (b - a) / k;

    cout << fixed << setprecision(6);
    cout << "Вычисление функции" << endl;
    cout << "y = (x^2/4 + x/2 + 1) * e^(x/2)" << endl;
    cout << "========================================" << endl;

    // Внешний цикл: изменение параметра x
    for (int i = 0; i <= k; ++i)    
    {
        double x = a + i * step;

        // ==========================================
        // 1. Вычисление суммы SN для заданного n=30
        // ==========================================
        double SN = 0.0;
        double term_N = 1.0;  // a_0 = 1

        for (int j = 0; j < N; ++j)
        {
            SN += term_N;
            // Рекуррентная формула: a_{j+1} = a_j * (j^2+2j+2) / ((j^2+1)*(j+1)) * (x/2)
            term_N = term_N * (j*j + 2*j + 2) / ((j*j + 1) * (j + 1)) * (x / 2);
        }

        // ==========================================
        // 2. Вычисление суммы SE с точностью eps
        // ==========================================
        double SE = 0.0;
        double term_E = 1.0;  // a_0 = 1
        int j = 0;  

        while (fabs(term_E) >= eps)
        {
            SE += term_E;
            term_E = term_E * (j*j + 2*j + 2) / ((j*j + 1) * (j + 1)) * (x / 2);
            j++;
        }

        // ==========================================
        // 3. Точное значение функции Y
        // ==========================================
        double Y = (x*x / 4 + x / 2 + 1) * exp(x / 2);

        // ==========================================
        // 4. Вывод результатов
        // ==========================================
        cout << "X = " << setw(10) << x << endl;
        cout << "SN = " << setw(10) << SN << endl;
        cout << "SE = " << setw(10) << SE << endl;
        cout << "Y  = " << setw(10) << Y << endl;
        cout << "----------------------------------------" << endl;
    }

    return 0;
}